"""Model metadata must describe the migrated schema exactly, comments included.

The defect this exists to prevent is real and already happened once. Three
migrations applied ``COMMENT ON COLUMN`` for columns on ``tasks`` and
``runtime_executions`` (``b3d5f7a9c1e2``, ``c8e1f3a5b7d9``, ``a4c7e2b9d1f3``),
but the corresponding ``mapped_column(...)`` declarations in
``src/kai/runtime/models.py`` and ``src/kai/tasks/models.py`` carried no
``comment=``. The database was therefore *richer* than the model metadata, and
``alembic check`` reported six ``modify_comment`` operations that would have
**removed** those descriptions had anyone autogenerated a migration from it.

That direction is the dangerous one: ``alembic check`` is only worth running if
it fails on real drift. A permanently-red check gets ignored, and the one thing
it was there to catch - someone altering a column without a migration - stops
being caught.

So this is asserted in both directions against the live database rather than
against the migration files: every comment the models declare must exist in
PostgreSQL with the same text, and every comment PostgreSQL holds must be
declared by a model. A column comment invented by a model and a comment dropped
by a model are both failures here.
"""

from __future__ import annotations

import pytest
from sqlalchemy import text

# Every model module registers its tables on ``Base.metadata`` as a side effect of
# being imported, so the parity below is only true if all of them are loaded.
# This mirrors ``alembic/env.py``: a module that exists and declares a table but
# is never imported here would report as drift the other way — the database holding
# a comment no model claims.
from kai.alerts import models as alert_models  # noqa: F401
from kai.approvals import models as approval_models  # noqa: F401
from kai.db import models as db_models  # noqa: F401
from kai.db.base import Base
from kai.db.engine import engine
from kai.memory import models as memory_models  # noqa: F401
from kai.planner import models as planner_models  # noqa: F401
from kai.runtime import models as runtime_models  # noqa: F401
from kai.tasks import models as task_models  # noqa: F401

#: Alembic's bookkeeping table. It is created by the migration runner, is not
#: part of application metadata, and carries no comments, so including it would
#: report a difference that is not one.
ALEMBIC_TABLE = "alembic_version"

_COLUMN_COMMENTS = """
SELECT c.relname AS table_name,
       a.attname AS column_name,
       col_description(c.oid, a.attnum) AS comment
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = 'public'
JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
WHERE c.relkind = 'r' AND col_description(c.oid, a.attnum) IS NOT NULL
"""

_TABLE_COMMENTS = """
SELECT c.relname AS table_name,
       obj_description(c.oid) AS comment
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = 'public'
WHERE c.relkind = 'r' AND obj_description(c.oid) IS NOT NULL
"""


def _model_table_comments() -> dict[str, str]:
    return {name: tbl.comment for name, tbl in Base.metadata.tables.items() if tbl.comment}


def _model_column_comments() -> dict[tuple[str, str], str]:
    return {
        (table_name, column.name): column.comment
        for table_name, tbl in Base.metadata.tables.items()
        for column in tbl.columns
        if column.comment
    }


async def _database_column_comments() -> dict[tuple[str, str], str]:
    async with engine.connect() as conn:
        rows = (await conn.execute(text(_COLUMN_COMMENTS))).all()
    return {(table, column): comment for table, column, comment in rows}


async def _database_table_comments() -> dict[str, str]:
    async with engine.connect() as conn:
        rows = (await conn.execute(text(_TABLE_COMMENTS))).all()
    return dict(rows)


async def test_declared_column_comments_exist_in_the_database() -> None:
    """A comment the model declares must be the comment the database holds."""
    live = await _database_column_comments()
    for key, comment in _model_column_comments().items():
        assert live.get(key) == comment, (
            f"{key[0]}.{key[1]} declares comment {comment!r} but the database holds "
            f"{live.get(key)!r}"
        )


async def test_database_column_comments_are_declared_by_the_models() -> None:
    """A comment the database holds must be declared, or ``check`` wants to drop it.

    This is the direction that actually bit: the six comments applied by
    ``b3d5f7a9c1e2``/``c8e1f3a5b7d9``/``a4c7e2b9d1f3`` were absent from the
    models, so autogenerate proposed deleting them.
    """
    declared = _model_column_comments()
    for key, comment in (await _database_column_comments()).items():
        assert declared.get(key) == comment, (
            f"{key[0]}.{key[1]} holds comment {comment!r} that no model declares; "
            f"alembic would generate a modify_comment removing it"
        )


async def test_table_comments_match_in_both_directions() -> None:
    live = await _database_table_comments()
    live.pop(ALEMBIC_TABLE, None)
    assert _model_table_comments() == live


async def test_the_six_previously_drifted_columns_are_covered() -> None:
    """Pin the specific regression, so it cannot be silently reintroduced.

    A general parity test passes just as happily when both sides lose a comment
    together. This asserts the six columns that drifted are declared, which is
    the part that was actually broken.
    """
    declared = _model_column_comments()
    expected = {
        ("runtime_executions", "plan_version"),
        ("runtime_executions", "plan_hash"),
        ("runtime_executions", "fulfillment_profile"),
        ("runtime_executions", "evaluator_version"),
        ("runtime_executions", "fulfillment_verdict"),
        ("tasks", "fulfillment_profile"),
    }
    assert expected <= set(declared)


@pytest.mark.parametrize("table", ["tasks", "runtime_executions"])
async def test_correcting_comments_did_not_move_any_ddl(table: str) -> None:
    """The fix must be metadata-only: no type, nullability or default changed.

    ``comment=`` is documentation. Column set and nullability are compared
    across *every* column on the two tables the decision touched, because those
    are the properties whose accidental movement would change DDL. Server
    defaults and types are asserted for the six corrected columns only.

    Server defaults are deliberately not compared across all columns.
    ``alembic/env.py`` does not set ``compare_server_default``, so Alembic does
    not treat them as drift, and six columns carry a database-side default the
    model does not declare (``runtime_executions.cursor`` -> ``0``,
    ``identities`` -> ``'[]'::jsonb``, and three others). Every one of those is a
    safety net for rows inserted outside the ORM while the model supplies the
    value client-side, so they are benign and are recorded as a known detection
    gap rather than "fixed" here. Asserting them as parity would be asserting a
    property the project has explicitly not chosen to hold.
    """
    async with engine.connect() as conn:
        rows = (
            await conn.execute(
                text(
                    "SELECT column_name, data_type, is_nullable, column_default "
                    "FROM information_schema.columns "
                    "WHERE table_schema = 'public' AND table_name = :table"
                ),
                {"table": table},
            )
        ).all()
    live = {row[0]: (row[1], row[2] == "YES", row[3]) for row in rows}
    metadata = Base.metadata.tables[table]
    assert set(live) == set(metadata.columns.keys())

    for name, column in metadata.columns.items():
        data_type, nullable, default = live[name]
        assert column.nullable is nullable, f"{table}.{name} nullability disagrees"

        if (table, name) not in _CORRECTED_COLUMN_TYPES:
            continue
        if column.server_default is None:
            assert default is None, f"{table}.{name} gained a server default"
        else:
            assert default is not None, f"{table}.{name} lost its server default"
        assert data_type == _CORRECTED_COLUMN_TYPES[(table, name)], (
            f"{table}.{name} is {data_type} in PostgreSQL, "
            f"expected {_CORRECTED_COLUMN_TYPES[(table, name)]}"
        )


#: PostgreSQL's own type names for exactly the six columns whose metadata this
#: round corrected. Recorded so that a future edit cannot quietly re-type one.
_CORRECTED_COLUMN_TYPES: dict[tuple[str, str], str] = {
    ("tasks", "fulfillment_profile"): "character varying",
    ("runtime_executions", "plan_version"): "integer",
    ("runtime_executions", "plan_hash"): "character varying",
    ("runtime_executions", "fulfillment_profile"): "character varying",
    ("runtime_executions", "evaluator_version"): "character varying",
    ("runtime_executions", "fulfillment_verdict"): "character varying",
}